"""Generate BCSync_Scheduler-clientdata.json.

BCSync_Scheduler (Oct 12, 2026) replaces the BC pulls' own timers now that they
run on Check BC now requests (_sync_request.py). Every 5 minutes, on the
:00 / :05 / ... marks, it adds a crfdf_syncrequest row (Requested By =
"Scheduler") for each kind that is due by Central time (SCHEDULE):

    taskcompletions   every 5 minutes        BCSync_TaskCompletions
    neworders         every 15 minutes       BCSync_NewOrders
    jobdescriptions   hourly                 BCSync_JobDescriptions
    jobpos            nightly 5:15           BCSync_JobPOs
    jobsketches       nightly 4:30           BCSync_JobSketches

Each pull deletes its scheduler row once done. Turn this flow off and the
pulls only run from the app's button.

    python _gen_sync_scheduler_flow.py

then build with _build_syncnow_solution.py. See flows/CHECK-BC-NOW.md.
"""
import json
import os

from _sync_request import DV, REQUESTS, SCHEDULE, SCHEDULER

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "BCSync_Scheduler-clientdata.json")

NOW = "convertFromUtc(utcNow(), 'Central Standard Time', '{f}')"
HH = f"int({NOW.format(f='HH')})"
MM = f"int({NOW.format(f='mm')})"


def due(rule):
    if rule == "true":
        return True
    return "@" + rule.replace("HH", HH).replace("mm", MM)


ITEM = "items('For_each_due_kind')"
actions = {
    "Kinds": {"type": "Compose", "runAfter": {},
              "inputs": [{"kind": k, "due": due(r)} for k, r in SCHEDULE.items()]},
    "Due_Kinds": {"type": "Query", "runAfter": {"Kinds": ["Succeeded"]},
                  "inputs": {"from": "@outputs('Kinds')", "where": "@equals(item()?['due'], true)"}},
    "For_each_due_kind": {
        "type": "Foreach", "foreach": "@body('Due_Kinds')", "runAfter": {"Due_Kinds": ["Succeeded"]},
        "actions": {"Request_A_Check": {
            "type": "OpenApiConnection", "runAfter": {},
            "inputs": {"parameters": {"entityName": REQUESTS,
                                      "item/crfdf_name": f"@{ITEM}?['kind']",
                                      "item/crfdf_kind": f"@{ITEM}?['kind']",
                                      "item/crfdf_status": "Requested",
                                      "item/crfdf_requestedby": SCHEDULER},
                       "host": {**DV, "operationId": "CreateRecord"}}}}},
}

flow = {
    "properties": {
        "connectionReferences": {
            "shared_commondataserviceforapps": {
                "api": {"name": "shared_commondataserviceforapps"},
                "connection": {"connectionReferenceLogicalName": "new_sharedcommondataserviceforapps_4a52d"},
                "runtimeSource": "embedded"},
        },
        "definition": {
            "$schema": "https://schema.management.azure.com/providers/Microsoft.Logic/schemas/2016-06-01/workflowdefinition.json#",
            "contentVersion": "1.0.0.0",
            "comment": ("BCSync_Scheduler - GENERATED by _gen_sync_scheduler_flow.py; edit that, not this. Every 5 "
                        "minutes asks the BC pulls that are due to run (crfdf_syncrequest rows). See CHECK-BC-NOW.md."),
            "parameters": {"$authentication": {"defaultValue": {}, "type": "SecureObject"},
                           "$connections": {"defaultValue": {}, "type": "Object"}},
            "triggers": {"Every_5_minutes": {
                "type": "Recurrence",
                # Started on a :00 so the runs land on the 5-minute marks the schedule counts on.
                "recurrence": {"frequency": "Minute", "interval": 5, "startTime": "2026-10-12T00:00:00Z"},
                "runtimeConfiguration": {"concurrency": {"runs": 1}}}},
            "actions": actions,
        },
    },
    "schemaVersion": "1.0.0.0",
}

with open(OUT, "w", encoding="utf-8") as f:
    json.dump(flow, f, indent=2, ensure_ascii=False)
    f.write("\n")
print("wrote", OUT)
